#endif

typedef struct LamoHttpRoute {
    char* path;
    char* body;
    struct LamoHttpRoute* next;
} LamoHttpRoute;

static LamoHttpRoute* lamo_http_routes = NULL;
static int lamo_http_runtime_initialized = 0;

static int lamo_http_init_runtime(void) {
#ifdef _WIN32
    WSADATA wsa_data;
    if (!lamo_http_runtime_initialized) {
        if (WSAStartup(MAKEWORD(2, 2), &wsa_data) != 0) {
            fprintf(stderr, "failed to initialize Winsock\n");
            return 0;
        }
        lamo_http_runtime_initialized = 1;
    }
#else
    lamo_http_runtime_initialized = 1;
#endif
    return 1;
}

static void lamo_http_add_route(const char* path, const char* body) {
    LamoHttpRoute* route;
    if (!lamo_http_init_runtime()) { return; }
    route = malloc(sizeof(LamoHttpRoute));
    if (!route) { fprintf(stderr, "failed to allocate HTTP route\n"); exit(1); }
    route->path = lamo_heap_strdup(path);
    route->body = lamo_heap_strdup(body);
    route->next = lamo_http_routes;
    lamo_http_routes = route;
}

static const LamoHttpRoute* lamo_http_find_route(const char* path) {
    LamoHttpRoute* current = lamo_http_routes;
    while (current) {
        if (strcmp(current->path, path) == 0) { return current; }
        current = current->next;
    }
    return NULL;
}

static int lamo_http_send_all(lamo_socket_t socket_fd, const char* data, int total_length) {
    int sent = 0;
    while (sent < total_length) {
        int chunk = send(socket_fd, data + sent, total_length - sent, 0);
        if (chunk <= 0) { return 0; }
        sent += chunk;
    }
    return 1;
}

static int lamo_http_send_response(lamo_socket_t client_socket, int status_code, const char* body) {
    char header[512];
    const char* reason = status_code == 200 ? "OK" : "Not Found";
    int body_length = (int)strlen(body);
    int header_length = snprintf(header, sizeof(header),
        "HTTP/1.1 %d %s\r\n"
        "Content-Type: text/plain; charset=utf-8\r\n"
        "Content-Length: %d\r\n"
        "Connection: close\r\n\r\n",
        status_code, reason, body_length);
    if (header_length < 0 || !lamo_http_send_all(client_socket, header, header_length)) {
        return 0;
    }
    return lamo_http_send_all(client_socket, body, body_length);
}

static void lamo_http_handle_client(lamo_socket_t client_socket) {
    char request[2048];
    char method[16];
    char path[1024];
    int received = recv(client_socket, request, (int)sizeof(request) - 1, 0);
    if (received <= 0) { return; }
    request[received] = '\0';
    method[0] = '\0';
    path[0] = '\0';
    if (sscanf(request, "%15s %1023s", method, path) == 2) {
        const LamoHttpRoute* route = lamo_http_find_route(path);
        if (route) {
            lamo_http_send_response(client_socket, 200, route->body);
            return;
        }
    }
    lamo_http_send_response(client_socket, 404, "not found");
}

static int lamo_http_run_server(int port, int serve_once) {
    lamo_socket_t server_socket;
    struct sockaddr_in address;
    int opt_value = 1;
    /* GC Step 4: HTTP server loop runs gc_collect() every N requests so
     * long-running http_serve() doesn't grow the arena without bound.
     * The interval (100) is conservative — typical Lamo HTTP programs
     * handle tens of req/sec, so this adds ~1ms of GC overhead per
     * second, well under the cost of a single request. */
    static const int HTTP_GC_INTERVAL = 100;
    long long request_count = 0;
    if (!lamo_http_init_runtime()) { return 0; }
    server_socket = socket(AF_INET, SOCK_STREAM, 0);
    if (server_socket == LAMO_INVALID_SOCKET) {
        fprintf(stderr, "failed to create HTTP socket\n");
        return 0;
    }
    setsockopt(server_socket, SOL_SOCKET, SO_REUSEADDR, (const char*)&opt_value, sizeof(opt_value));
    memset(&address, 0, sizeof(address));
    address.sin_family = AF_INET;
    address.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
    address.sin_port = htons((unsigned short)port);
    if (bind(server_socket, (struct sockaddr*)&address, sizeof(address)) != 0) {
        fprintf(stderr, "failed to bind HTTP server on port %d\n", port);
        lamo_close_socket(server_socket);
        return 0;
    }
    if (listen(server_socket, 8) != 0) {
        fprintf(stderr, "failed to listen on HTTP server port %d\n", port);
        lamo_close_socket(server_socket);
        return 0;
    }
    while (1) {
        lamo_socket_t client_socket = accept(server_socket, NULL, NULL);
        if (client_socket == LAMO_INVALID_SOCKET) { break; }
        lamo_http_handle_client(client_socket);
        lamo_close_socket(client_socket);
        if (serve_once) { break; }
        /* Periodic GC: every HTTP_GC_INTERVAL requests, reclaim
         * unreachable allocations. The route table (registered via
         * http_route) lives in `lamo_http_routes`, which is a separate
         * malloc'd linked list NOT tracked by the GC — so routes stay
         * alive across collections. Only per-request garbage (string
         * buffers built while parsing/handling) gets swept. */
        if (++request_count >= HTTP_GC_INTERVAL) {
            request_count = 0;
            lamo_gc_collect();
        }
    }
    lamo_close_socket(server_socket);
    return 1;
}

